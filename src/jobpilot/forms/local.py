"""Local-only entrypoint that applies to an approved job through its ATS form.

This is the user-reachable bridge between the normal proposal/approval flow and the
assisted-form filler. It is LOCAL ONLY and is never invoked from the scheduled CI
pipeline: it opens a real browser (Playwright) on the owner's machine. The CLI
``jobpilot apply-form <job_id>`` command calls :func:`apply_to_approved_job_via_form`.

The flow is deliberately strict so an assisted submission carries exactly the same
guarantees an email send does:

* the job must be ``approved`` and must use a supported platform (Greenhouse/Lever);
  LinkedIn Easy Apply and Indeed are rejected before any browser opens;
* the exact APPROVED documents the owner reviewed in the proposal are reused (the CV
  and cover-letter PDF bytes are written to temp files and uploaded; the cover-letter
  text is placed in a platform's additional-information control when there is no
  dedicated upload — never a letter regenerated by the LLM);
* the CV variant and both document URLs the owner saw are REQUIRED and passed to the
  guarded flow, so a recorded form application has the same tracking fields (R12.6);
* the pre-submit Telegram confirmation, the safe-abort / CAPTCHA stop, the durable
  per-job submit claim and the atomic finalize all come from
  :func:`jobpilot.forms.apply.apply_via_form`.
"""

from __future__ import annotations

import tempfile
from pathlib import Path
from typing import TYPE_CHECKING

from jobpilot.forms.apply import FormApplyResult, FormApplyStatus, apply_via_form
from jobpilot.forms.base import Platform, detect_platform, is_unsupported_url
from jobpilot.forms.greenhouse import GreenhouseFormFiller
from jobpilot.forms.lever import LeverFormFiller
from jobpilot.logging import get_logger
from jobpilot.models import JobStatus

if TYPE_CHECKING:
    from jobpilot.config import AppConfig
    from jobpilot.forms.base import FormFiller
    from jobpilot.interfaces import LlmClient, Notifier
    from jobpilot.pipeline.run import ProposalArtifacts, ProposalRepository
    from jobpilot.profile.model import ProfileModel

log = get_logger(__name__)


def _build_filler(
    platform: str, profile: ProfileModel, llm: LlmClient, config: AppConfig, analysis: object
) -> FormFiller:
    """Construct the FormFiller for ``platform`` with the offer analysis.

    The analysis is passed so the LLM can answer non-sensitive open questions from
    the profile and THIS offer only. New platforms are added by registering another
    branch here (and a matching ``FormFiller``).
    """
    from jobpilot.models import JobAnalysis

    typed_analysis = analysis if isinstance(analysis, JobAnalysis) else None
    if platform == Platform.greenhouse.value:
        return GreenhouseFormFiller(profile, llm, config.forms, analysis=typed_analysis)
    if platform == Platform.lever.value:
        return LeverFormFiller(profile, llm, config.forms, analysis=typed_analysis)
    raise ValueError(f"no assisted-form filler for platform {platform!r}")


def apply_to_approved_job_via_form(
    job_id: int,
    repo: ProposalRepository,
    notifier: Notifier,
    profile: ProfileModel,
    llm: LlmClient,
    config: AppConfig,
) -> FormApplyResult:
    """Apply to approved ``job_id`` through its supported ATS form (LOCAL only).

    Loads the job and its approved proposal artifacts, selects the platform from the
    apply URL, builds the matching filler with the offer analysis, writes the exact
    approved CV/cover PDFs to temp files and runs the guarded fill -> confirm ->
    submit -> record flow. Returns the :class:`FormApplyResult`; the job must be
    ``approved`` and the platform supported, otherwise the flow stops early and
    nothing is submitted or recorded.
    """
    from jobpilot.pipeline.run import _load_proposal_artifacts  # noqa: PLC0415 - avoid cycle

    job = repo.get_job(job_id)
    if job is None:
        notifier.send_message(f"No encontré la oferta {job_id}.")
        return FormApplyResult(status=FormApplyStatus.unsupported)
    if job.status is not JobStatus.approved:
        notifier.send_message(
            f"La oferta {job_id} no está aprobada (estado: {job.status.value}); no la postulo."
        )
        return FormApplyResult(status=FormApplyStatus.already_claimed)

    url = job.apply_url or job.url
    if is_unsupported_url(url):
        notifier.send_message(
            f"La oferta {job_id} es de LinkedIn/Indeed (fuera de alcance); aplícala manualmente."
        )
        return FormApplyResult(status=FormApplyStatus.unsupported)
    # A URL match gives the platform up front; an unknown (non-LinkedIn/Indeed) URL is
    # NOT rejected here — an embedded Greenhouse/Lever form on a company careers domain
    # is only visible in the rendered DOM, so the page is opened and detected inside
    # ``apply_via_form`` via a filler factory (P8-012).
    url_platform = detect_platform(url)

    artifacts = _load_proposal_artifacts(repo, job)
    if artifacts.cv is None or artifacts.cover_letter is None:
        notifier.send_message(
            f"No tengo los documentos aprobados de la oferta {job_id}; no puedo postular por "
            "formulario sin ellos."
        )
        return FormApplyResult(status=FormApplyStatus.unsupported)

    language = job.language or artifacts.language

    # When the URL identifies the platform, build the filler up front. Otherwise defer
    # to a factory that ``apply_via_form`` calls AFTER detecting the rendered DOM, so
    # an embedded Greenhouse/Lever form on a company domain is handled on the same
    # guarded page (P8-012). Anything the DOM still cannot identify is applied manually.
    def make_filler(platform: str) -> FormFiller:
        return _build_filler(platform, profile, llm, config, job.analysis)

    filler = make_filler(url_platform) if url_platform is not None else None
    filler_factory = None if url_platform is not None else make_filler

    # Write the exact approved PDFs to temp files for upload; they are removed when
    # the flow returns. The cover-letter TEXT is passed for platforms with no
    # dedicated upload (Lever) so the approved letter is placed, never regenerated.
    with tempfile.TemporaryDirectory(prefix="jobpilot-form-") as tmp:
        tmp_dir = Path(tmp)
        cv_path = _write_temp(tmp_dir, artifacts.cv.filename, artifacts.cv.content)
        cover_path = _write_temp(
            tmp_dir, artifacts.cover_letter.filename, artifacts.cover_letter.content
        )
        log.info("form_local_apply_start", job_id=job_id, url_platform=url_platform)
        return apply_via_form(
            job,
            filler,
            notifier,
            repo,
            config,
            language=language,
            cv_path=str(cv_path),
            cover_letter_path=str(cover_path),
            cv_variant=artifacts.cv_variant,
            cv_url=_require_url(artifacts, "cv_url"),
            cover_letter_url=_require_url(artifacts, "cover_letter_url"),
            cover_letter_text=artifacts.cover_letter_body or None,
            filler_factory=filler_factory,
        )


def _write_temp(tmp_dir: Path, filename: str, content: bytes) -> Path:
    """Write ``content`` to ``tmp_dir/filename`` and return the path."""
    path = tmp_dir / filename
    path.write_bytes(content)
    return path


def _require_url(artifacts: ProposalArtifacts, attr: str) -> str:
    """Return a required document URL from the artifacts, erroring if absent.

    R12.6 requires a recorded form application to carry both document URLs, so a
    proposal missing one cannot proceed to an assisted submission.
    """
    value = getattr(artifacts, attr)
    if not value:
        raise ValueError(f"approved proposal is missing {attr}; cannot apply by form")
    return str(value)
